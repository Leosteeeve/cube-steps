export function tourForRoute(route: ClubRoute, playableLesson: boolean): TourId | null {
  if (route.kind === 'learn') return playableLesson ? 'lesson-player' : 'lesson-intro';
  return route.kind in TOURS ? (route.kind as TourId) : null;
}
